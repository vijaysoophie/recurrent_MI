"""
chow_model.py -- core engine for reproducing

    Chow S-F, Wick SD, Riecke H (2012)
    "Neurogenesis Drives Stimulus Decorrelation in a Model of the Olfactory Bulb"
    PLoS Comput Biol 8(3): e1002398.

This file is generated by 01_model_core.ipynb (%%writefile).  Do not edit by hand;
edit the notebook and re-run it.

Model (METHODS, "Discrete Adaptive Network Model"):

    steady state of eqs.(3,4) with linear coupling

        M^(a) = (I + W^(mg) W^(gm))^{-1} (Msp + S^(a))          (mitral, Nm)
        G^(a) = W^(gm) M^(a)                                     (granule, Ng)

    W^(gm)_{jk} = 1 if granule j receives input from mitral k, else 0
    W^(mg)_{ij} = w * (reciprocity, eq.(6)) -- granule j inhibits the mitral
                  cells that drive it.

    resilience        R_j = sum_a [ G^(a)_j - Gmin ]_+           (eq. 8)
    survival prob.    p(R) = 1/2 { tanh( gamma (R - R0) ) + 1 }  (eq. 9)

    Each time step (DT = 1): add `b` new granule cells with `nconnect` random
    mitral partners, recompute the steady state, then remove each granule cell
    with probability 1 - p(R).
"""

import numpy as np
from scipy.linalg import cho_factor, cho_solve

__all__ = ["ChowNetwork", "pearson_corr_matrix", "mean_corr", "top_corr"]


# ----------------------------------------------------------------------------- 
# correlation measures, eqs.(10,11)
# -----------------------------------------------------------------------------
def pearson_corr_matrix(M):
    """Pearson correlation between activity patterns.  M has shape (Nm, Ns)."""
    Z = M - M.mean(axis=0, keepdims=True)
    n = np.linalg.norm(Z, axis=0)
    n[n == 0] = 1.0
    Z = Z / n
    return Z.T @ Z


def mean_corr(C):
    """Average correlation rho_bar over all ordered pairs a != b, eq.(11)."""
    Ns = C.shape[0]
    return (C.sum() - np.trace(C)) / (Ns * (Ns - 1))


def top_corr(C, pairs):
    """Mean correlation of the 'highly similar' stimulus pairs (enantiomers)."""
    return float(np.mean([C[i, j] for i, j in pairs]))


# -----------------------------------------------------------------------------
# the network
# -----------------------------------------------------------------------------
class ChowNetwork:
    """Discrete adaptive network of mitral and granule cells.

    Parameters
    ----------
    S : (Ns, Nm) array
        Stimulus ensemble that drives the network evolution (glomerular input).
    Nm : int
        Number of mitral cells / input channels.
    nconnect : int
        Number of mitral cells each new granule cell connects to.
    b : float
        Influx of new granule cells per time step.
    w : float
        Strength of every inhibitory (granule -> mitral) synapse.
    Msp : float
        Spontaneous mitral activity.
    Gmin : float
        Resilience threshold, eq.(8).
    R0 : float
        Soft survival threshold, eq.(9).
    gamma : float
        Steepness of the survival curve, eq.(9).
    rng : np.random.Generator
    reciprocity : float in [0, 1]
        Fraction of inhibitory synapses that stay reciprocal (RESULTS,
        "Imperfect Reciprocity of Synapses Is Sufficient", Fig.7A).
        1 - reciprocity of them are redirected to a random mitral cell.
    dw : float
        Heterogeneity of inhibitory weights (Fig.7B).  Weights are drawn with
        equal probability from {w - dw, w + dw} ("two-point"), or uniformly from
        [w - dw, w + dw] ("uniform"); see `dw_mode`.
    dw_mode : {"two-point", "uniform"}
    delta : float or None
        Self- vs lateral-inhibition balance (Fig.7C).  If not None the effective
        connectivity is rescaled row-wise,
            W_ii -> delta * W_ii / N ,  W_ij -> (1 - delta) * W_ij / N ,
        with N chosen per row so that the row sum is unchanged.
    """

    def __init__(self, S, Nm, nconnect, b, w, Msp, Gmin, R0, gamma,
                 rng=None, reciprocity=1.0, dw=0.0, dw_mode="two-point",
                 delta=None):
        self.S = np.atleast_2d(np.asarray(S, dtype=float))   # (Ns, Nm)
        self.Ns, self.Nm_S = self.S.shape
        assert self.Nm_S == Nm, "stimulus dimension does not match Nm"
        self.Nm = int(Nm)
        self.nconnect = int(nconnect)
        self.b = float(b)
        self.w = float(w)
        self.Msp = float(Msp)
        self.Gmin = float(Gmin)
        self.R0 = float(R0)
        self.gamma = float(gamma)
        self.reciprocity = float(reciprocity)
        self.dw = float(dw)
        self.dw_mode = dw_mode
        self.delta = delta
        self.rng = np.random.default_rng() if rng is None else rng

        # drive to the mitral cells, (Nm, Ns)
        self.drive = (self.Msp + self.S).T

        # granule cell book-keeping
        self.exc = np.zeros((0, self.nconnect), dtype=np.int32)  # W^(gm) targets
        self.inh = np.zeros((0, self.nconnect), dtype=np.int32)  # W^(mg) targets
        self.wts = np.zeros((0, self.nconnect), dtype=float)     # inhib. weights
        self.age = np.zeros(0, dtype=np.int64)                   # birth step
        self.t = 0

        self._symmetric = (self.reciprocity >= 1.0 and self.dw == 0.0
                           and self.delta is None)

        # cached effective connectivity, maintained incrementally
        self._W = np.zeros((self.Nm, self.Nm))
        self._since_rebuild = 0

        # rounding carry, so that a non-integer influx b is honoured on average
        self._carry = 0.0

    # ------------------------------------------------------------------ helpers
    def set_stimuli(self, S):
        """Replace the stimulus ensemble that drives the network evolution.

        Used for the enrichment protocols of Figs. 9 and 10, where the ensemble
        changes part-way through a run.
        """
        self.S = np.atleast_2d(np.asarray(S, dtype=float))
        assert self.S.shape[1] == self.Nm
        self.Ns = self.S.shape[0]
        self.drive = (self.Msp + self.S).T

    @property
    def Ng(self):
        return self.exc.shape[0]

    def _random_connections(self, n):
        """n x nconnect distinct random mitral partners (no double synapses)."""
        if n == 0:
            return np.zeros((0, self.nconnect), dtype=np.int32)
        if self.nconnect == 1:
            return self.rng.integers(0, self.Nm, size=(n, 1)).astype(np.int32)
        # vectorised "choose nconnect out of Nm without replacement"
        out = self.rng.random((n, self.Nm)).argpartition(
            self.nconnect - 1, axis=1)[:, :self.nconnect]
        return out.astype(np.int32)

    def add_cells(self, n=None, mark=False):
        """Add new granule cells with random connections (neurogenesis)."""
        if n is None:
            x = self.b + self._carry
            n = int(np.floor(x))
            self._carry = x - n
        if n <= 0:
            return 0
        exc = self._random_connections(n)

        # inhibitory targets: reciprocal (eq.6), possibly partly rewired (Fig.7A)
        inh = exc.copy()
        if self.reciprocity < 1.0:
            rewire = self.rng.random(inh.shape) > self.reciprocity
            inh[rewire] = self.rng.integers(0, self.Nm, size=int(rewire.sum()))

        # inhibitory strengths (Fig.7B)
        if self.dw == 0.0:
            wts = np.full(exc.shape, self.w)
        elif self.dw_mode == "two-point":
            wts = self.w + self.dw * self.rng.choice([-1.0, 1.0], size=exc.shape)
        else:
            wts = self.rng.uniform(self.w - self.dw, self.w + self.dw,
                                   size=exc.shape)

        self.exc = np.vstack([self.exc, exc])
        self.inh = np.vstack([self.inh, inh])
        self.wts = np.vstack([self.wts, wts])
        self.age = np.concatenate([self.age, np.full(n, self.t, dtype=np.int64)])
        self._accumulate(exc, inh, wts, +1.0)
        return n

    # ------------------------------------------------------------- connectivity
    def _accumulate(self, exc, inh, wts, sign):
        """Add (sign=+1) or remove (sign=-1) these cells' contribution to W."""
        if exc.shape[0] == 0:
            return
        Nm = self.Nm
        idx = (inh[:, :, None].astype(np.int64) * Nm
               + exc[:, None, :].astype(np.int64))
        vals = np.broadcast_to(wts[:, :, None], idx.shape)
        self._W += sign * np.bincount(idx.ravel(), weights=vals.ravel(),
                                      minlength=Nm * Nm).reshape(Nm, Nm)

    def rebuild_W(self):
        self._W = self._effective_W_full()
        self._since_rebuild = 0
        return self._W

    def _effective_W_full(self):
        """Effective mitral-mitral connectivity W = W^(mg) W^(gm), eq.(7)."""
        Nm = self.Nm
        if self.Ng == 0:
            return np.zeros((Nm, Nm))
        idx = (self.inh[:, :, None].astype(np.int64) * Nm
               + self.exc[:, None, :].astype(np.int64))
        vals = np.broadcast_to(self.wts[:, :, None], idx.shape)
        W = np.bincount(idx.ravel(), weights=vals.ravel(),
                        minlength=Nm * Nm).reshape(Nm, Nm)
        return W

    def effective_W(self):
        """Effective mitral-mitral connectivity W = W^(mg) W^(gm), eq.(7)."""
        if self._since_rebuild > 2000:
            self.rebuild_W()
        return self._W

    def _rescaled_W(self, W):
        """Fig.7C: shift the balance between self- and lateral inhibition."""
        if self.delta is None:
            return W
        d = float(self.delta)
        diag = np.diag(W).copy()
        rowsum = W.sum(axis=1)
        off = rowsum - diag
        newrow = d * diag + (1.0 - d) * off
        norm = np.where(newrow > 0, newrow / np.where(rowsum > 0, rowsum, 1.0), 1.0)
        norm[norm == 0] = 1.0
        Wn = (1.0 - d) * W / norm[:, None]
        Wn[np.diag_indices_from(Wn)] = d * diag / norm
        return Wn

    # --------------------------------------------------------------- activities
    def steady_state(self, S=None, W=None):
        """Steady-state mitral activities, (Nm, Ns_test)."""
        if W is None:
            W = self._rescaled_W(self.effective_W())
        drive = self.drive if S is None else (self.Msp + np.atleast_2d(S)).T
        A = np.eye(self.Nm) + W
        if self._symmetric:
            # with full reciprocity and homogeneous weights 1 + W is symmetric
            # positive definite, so a Cholesky factorisation is both faster and
            # better conditioned than a general LU solve.
            try:
                return cho_solve(cho_factor(A, lower=True, check_finite=False),
                                 drive, check_finite=False)
            except np.linalg.LinAlgError:
                pass
        return np.linalg.solve(A, drive)

    def granule_activity(self, M):
        """G^(a)_j = sum_k W^(gm)_{jk} M^(a)_k, eq.(4), shape (Ng, Ns)."""
        if self.Ng == 0:
            return np.zeros((0, M.shape[1]))
        return M[self.exc].sum(axis=1)

    def resilience(self, G):
        return np.maximum(G - self.Gmin, 0.0).sum(axis=1)          # eq.(8)

    def survival_prob(self, R):
        return 0.5 * (np.tanh(self.gamma * (R - self.R0)) + 1.0)   # eq.(9)

    # --------------------------------------------------------------- one update
    def step(self, prune=True, record=None):
        """One time step DT = 1: neurogenesis, steady state, apoptosis."""
        self.t += 1
        n_in = self.add_cells()

        W = self._rescaled_W(self.effective_W())
        M = self.steady_state(W=W)
        G = self.granule_activity(M)
        R = self.resilience(G)
        p = self.survival_prob(R)

        info = {"t": self.t, "Ng": self.Ng, "influx": n_in, "M": M,
                "G": G, "R": R, "p": p, "W": W}

        if prune and self.Ng:
            keep = self.rng.random(self.Ng) < p
            info["removed"] = int((~keep).sum())
            info["keep"] = keep
            drop = ~keep
            if drop.any():
                self._accumulate(self.exc[drop], self.inh[drop],
                                 self.wts[drop], -1.0)
                self._since_rebuild += 1
            self.exc = self.exc[keep]
            self.inh = self.inh[keep]
            self.wts = self.wts[keep]
            self.age = self.age[keep]
        else:
            info["removed"] = 0
            info["keep"] = np.ones(self.Ng, dtype=bool)
        info["Ng_after"] = self.Ng
        if record is not None:
            record(info)
        return info

    def run(self, nsteps, record=None, callback_every=1, progress=None):
        out = []
        for k in range(nsteps):
            info = self.step()
            if record is not None and (self.t % callback_every == 0):
                out.append(record(self, info))
            if progress is not None and (self.t % progress == 0):
                print(f"  t={self.t:5d}  Ng={self.Ng:7d}  "
                      f"removed/influx={info['removed']/max(info['influx'],1):.2f}",
                      flush=True)
        return out
